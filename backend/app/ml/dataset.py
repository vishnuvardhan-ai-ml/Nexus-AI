def generate_synthetic_benchmark_dataset(
    n_samples: int = 1200,
    random_state: int = 42,
    noise_std: float = 2.5,
) -> pd.DataFrame:
    """
    Generate a balanced, reproducible synthetic benchmark dataset across civic hazard categories.

    LABEL GENERATION METHODOLOGY:
    Each synthetic sample generates H, E, V, D based on domain-derived scenarios with Gaussian noise.
    The continuous synthetic score is:
        Score = 0.4*H + 0.3*E + 0.2*V + 0.1*D + eps, where eps ~ N(0, noise_std^2)
    Bounded to [0.0, 100.0].
    The label is classified strictly by the operational boundaries:
        - LOW:    0.0 <= Score < 30.0
        - MEDIUM: 30.0 <= Score < 60.0
        - HIGH:   60.0 <= Score <= 100.0

    DISCLOSURE:
    The model trained on this dataset learns to predict risk levels derived from the
    authoritative weighted formula with civic domain features. It is NOT real historical disaster
    data and does NOT predict real-world disasters with physical certainty.
    """
    rng = np.random.default_rng(seed=random_state)
    records = []
    samples_per_category = n_samples // len(CATEGORIES)

    for cat in CATEGORIES:
        templates = INCIDENT_TEMPLATES[cat]
        for i in range(samples_per_category):
            # Select base scenario template
            t_idx = i % len(templates)
            tmpl = templates[t_idx]

            # Sample factor values with realistic variance around scenario baselines
            h = float(np.clip(tmpl["base_h"] + rng.normal(0, 7.5), 0.0, 100.0))
            e = float(np.clip(tmpl["base_e"] + rng.normal(0, 7.5), 0.0, 100.0))
            v = float(np.clip(tmpl["base_v"] + rng.normal(0, 6.0), 0.0, 100.0))
            d = float(np.clip(tmpl["base_d"] + rng.normal(0, 8.0), 0.0, 100.0))

            # Round to 1 decimal place
            h = round(h, 1)
            e = round(e, 1)
            v = round(v, 1)
            d = round(d, 1)

            # Generate synthetic score using deterministic rule + civic noise
            raw_formula_score = (0.4 * h) + (0.3 * e) + (0.2 * v) + (0.1 * d)
            noise = float(rng.normal(0, noise_std))
            composite_score = float(np.clip(raw_formula_score + noise, 0.0, 100.0))
            composite_score = round(composite_score, 2)

            # Classify into exact boundaries
            if composite_score < 30.0:
                risk_level = RiskLevel.LOW.value
            elif composite_score < 60.0:
                risk_level = RiskLevel.MEDIUM.value
            else:
                risk_level = RiskLevel.HIGH.value

            # Add slight phrasing variations to descriptions for robust TF-IDF training
            desc_text = tmpl["desc"]
            if i % 3 == 0:
                desc_text += " Civic personnel notified."
            elif i % 3 == 1:
                desc_text += " Priority assessment in progress."

            combined_text = f"{tmpl['title']}. {desc_text}"

            records.append({
                "sample_id": f"synth_{cat[:3]}_{i:04d}",
                "dataset_label": DATASET_DISCLOSURE_LABEL,
                "category": cat,
                "title": tmpl["title"],
                "description": desc_text,
                "text_content": combined_text,
                "hazard_severity": h,
                "exposure": e,
                "vulnerability": v,
                "duration": d,
                "formula_raw_score": round(raw_formula_score, 2),
                "synthetic_noise": round(noise, 2),
                "composite_score": composite_score,
                "risk_level": risk_level,
                "is_synthetic": True,
            })

    df = pd.DataFrame(records)
    return df


def get_train_test_split(
    df: pd.DataFrame,
    test_size: float = 0.2,
    random_state: int = 42,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.Series, pd.Series]:
    """
    Split synthetic benchmark dataset into stratified train and test sets.
    Stratification ensures balanced LOW, MEDIUM, and HIGH representation across splits.
    Avoids data leakage by isolating text, tabular features, and labels.
    """
    feature_cols = [
        "title",
        "description",
        "text_content",
        "category",
        "hazard_severity",
        "exposure",
        "vulnerability",
        "duration",
    ]
    target_col = "risk_level"

    X = df[feature_cols]
    y = df[target_col]

    X_train, X_test, y_train, y_test = train_test_split(
        X,
        y,
        test_size=test_size,
        random_state=random_state,
        stratify=y,
    )

    return X_train, X_test, y_train, y_test
